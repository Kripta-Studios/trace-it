const { chromium, expect } = require('../../frontend/node_modules/@playwright/test')
const fs = require('node:fs')
const path = require('node:path')
const base = 'http://127.0.0.1:18174/nexia/trace-it/'
const grant = Number(process.env.TRACE_SETTINGS_PROCESS_ID || 3)
const results = []
;(async () => {
 const browser = await chromium.launch({headless:true})
 const context = await browser.newContext({ viewport:{width:1280,height:900} })
 const page = await context.newPage()
 page.setDefaultTimeout(15000)
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 const record=(scenario,evidence)=>{results.push({scenario,evidence});console.log(scenario,JSON.stringify(evidence))}
 const visit=async p=>{await page.goto(new URL(p,base).href);await page.waitForLoadState('networkidle')}
 try {
  await visit(`processes/${grant}/settings?tab=modelos`)
  await page.getByRole('combobox',{name:'Preview a preset'}).selectOption('balanced')
  await page.getByRole('button',{name:'Apply to editor',exact:true}).click()
  const compiler=page.locator('details').filter({has:page.locator('summary').filter({hasText:/^compiler /})}).first()
  await compiler.locator('summary').click()
  const parameters=compiler.locator('textarea').first()
  await parameters.fill('{invalid')
  record('invalid model parameters block save',await page.getByRole('button',{name:'Save draft and validate',exact:true}).isDisabled())
  await parameters.fill('{}')
  const save=page.waitForResponse(r=>r.url().endsWith(`/processes/${grant}/draft`)&&r.request().method()==='PUT')
  await page.getByRole('button',{name:'Save draft and validate',exact:true}).click()
  const saved=await save;record('model settings save response',{status:saved.status(),body:await saved.json()})
  await page.waitForTimeout(2000)
  record('draft validation UI',(await page.locator('body').innerText()).slice(-1500))
  await visit(`processes/${grant}/settings?tab=modelos`)
  record('saved preset reread',await page.getByText('Current configuration:',{exact:false}).innerText())
  await visit('processes/1/definition/fuentes')
  const upload=page.locator('input[type=file]').first()
  await page.getByLabel('Fecha de corte').fill('2026-09-18')
  let response=page.waitForResponse(r=>r.url().endsWith('/sources/workbook'))
  await upload.setInputFiles(path.resolve('.context/500-sombras-de-alberto/FINAL_v7_DEFINITIVO_ahorasi.xlsx'))
  let r=await response;record('reference workbook upload',{status:r.status(),body:await r.json()})
  await expect(page.getByRole('cell',{name:'parameters',exact:true})).toBeVisible()
  await expect(page.getByLabel('Fecha de corte')).toHaveValue('2026-09-18')
  await page.getByLabel('Fecha de corte').fill('2026-09-19')
  response=page.waitForResponse(r=>r.url().endsWith('/sources/workbook'))
  await upload.setInputFiles(path.resolve('.context/500-sombras-de-alberto/FINAL_v7_DEFINITIVO_ahorasi.xlsx'))
  r=await response;record('reference workbook repeat with updated cutoff',{status:r.status(),body:await r.json()})
  await page.reload()
  await expect(page.getByLabel('Fecha de corte')).toHaveValue('2026-09-19')
  record('changed cutoff persists after reload',await page.getByLabel('Fecha de corte').inputValue())
  await visit(`processes/${grant}/definition/fuentes`)
  await page.getByLabel('Fecha de corte').fill('2026-10-18')
  response=page.waitForResponse(r=>r.url().endsWith('/sources/workbook'))
  await page.locator('input[type=file]').first().setInputFiles({name:'invalid.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:Buffer.from('not an XLSX')})
  r=await response;record('invalid workbook visible failure',{status:r.status(),body:await r.json()})
  await expect(page.getByText('Invalid or unsupported workbook',{exact:true})).toBeVisible()
  response=page.waitForResponse(r=>r.url().endsWith('/sources/workbook'))
  await page.locator('input[type=file]').first().setInputFiles('/tmp/trace-grant-sources.xlsx')
  r=await response;record('grant custom unicode workbook',{status:r.status(),body:await r.json()})
  await visit('settings')
  await page.getByRole('button',{name:/^(Dark|Oscuro)$/}).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark')
  await page.reload();record('dark theme survives reload',await page.locator('html').getAttribute('data-theme'))
  await page.setViewportSize({width:390,height:844})
  record('settings mobile horizontal fit',await page.evaluate(()=>({viewport:innerWidth,width:document.documentElement.scrollWidth})))
  record('runtime errors',errors)
 }catch(error){process.exitCode=1;record('audit exception',String(error));await page.screenshot({path:'/tmp/trace-settings-features-failure.png',fullPage:true})}
 finally{fs.writeFileSync('/tmp/trace-settings-features.json',JSON.stringify(results,null,2));await browser.close()}
})()
