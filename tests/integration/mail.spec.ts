import { expect, test } from '@playwright/test'

const API = process.env.MAIL_TEST_API_URL ?? 'http://127.0.0.1:18285'

test('mail settings show automatic outcomes, notices and attachment retry with preserved history', async ({ page, request }, testInfo) => {
  test.setTimeout(90_000)
  const state = await (await request.get(`${API}/_mail-test/state`)).json()
  const root = `${API}/processes/${state.process_id}/mail-ingestion`
  const headers = { 'X-User-Id': String(state.user_id) }
  const overview = async () => (await request.get(root, { headers })).json()
  await page.goto(`/processes/${state.process_id}/settings`)
  const email = page.getByLabel('Buzón que alimenta el proceso')
  await expect(email).toHaveValue('')
  const saved = page.waitForResponse(response => response.url().endsWith('/gathering') && response.request().method() === 'PUT')
  await email.selectOption('migration-test@j-aautomation.com')
  expect((await saved).ok()).toBe(true)
  await page.reload()
  await expect(email).toHaveValue('migration-test@j-aautomation.com')
  await expect(page.getByText('Pendiente de inicializar', { exact: true })).toBeVisible()
  const start = await request.post(`${API}/_mail-test/start`)
  expect(start.ok(), await start.text()).toBeTruthy()
  // Old reception bookmarks still reach the current mail settings.
  await page.goto(`/processes/${state.process_id}/reception`)
  await expect(page).toHaveURL(new RegExp(`/processes/${state.process_id}/settings$`))
  await expect.poll(async () => (await (await request.get(`${root}/activity`, { headers })).json()).initialized).toBe(true)
  expect((await request.post(`${API}/_mail-test/deliver`)).ok()).toBeTruthy()
  const message = page.locator('li[id^="mail-"]').filter({ hasText: 'Synthetic automatic invoice batch' })
  await expect(message).toBeVisible()
  await expect(message.getByRole('link', { name: 'Abrir', exact: true })).toHaveCount(3)
  await expect(message.getByText('· Requiere revisión', { exact: true })).toHaveCount(1)
  await expect(message.getByText('· No se pudo procesar', { exact: true })).toHaveCount(0)
  const delivered = (await overview()).messages.find((item: any) => item.envelope.subject === 'Synthetic automatic invoice batch')
  expect(delivered.attachments.map((part: any) => part.decision).sort()).toEqual(['ESCALAR', 'NO_PAGAR', 'PAGAR'])
  const toast = page.getByRole('status').filter({ hasText: 'Correo procesado' })
  await expect(toast).toHaveCount(1)
  await expect(toast).toContainText('1 PDF requieren revisión')
  await page.reload()
  await expect(message).toBeVisible()
  await expect(toast).toHaveCount(0)
  const history = await (await request.get(`${root}/messages/${delivered.id}/history`, { headers })).json()
  expect(history.activities.filter((event: any) => event.kind === 'reading')).toHaveLength(3)
  expect(history.activities.some((event: any) => event.kind === 'completed')).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('mail-settings.png'), fullPage: true })

  expect((await request.post(`${API}/_mail-test/deliver-duplicates`)).ok()).toBeTruthy()
  const duplicate = page.locator('li[id^="mail-"]').filter({ hasText: 'Duplicate receipt must retain its original decision' })
  await expect(duplicate.getByText('· Ya registrado', { exact: true })).toBeVisible()
  await expect(duplicate.getByRole('link', { name: 'Abrir', exact: true })).toHaveCount(1)
  const informational = page.locator('li[id^="mail-"]').filter({ hasText: 'Informational message without attachments' })
  await expect(informational.getByText('Sin PDF adjunto', { exact: true })).toBeVisible()
  const duplicateRow = (await overview()).messages.find((item: any) => item.envelope.subject === 'Duplicate receipt must retain its original decision')
  const original = delivered.attachments.find((part: any) => part.original_name === 'pay.pdf')
  expect(duplicateRow.attachments[0].instance_id).toBe(original.instance_id)
  expect(duplicateRow.attachments[0].decision_id).toBe(original.decision_id)

  expect((await request.post(`${API}/_mail-test/deliver-retry`)).ok()).toBeTruthy()
  const retry = page.locator('li[id^="mail-"]').filter({ hasText: 'Retry one attachment' })
  await expect(retry.getByText('· No se pudo procesar', { exact: true })).toBeVisible()
  await expect(retry.getByTitle('No se ha podido abrir este PDF.', { exact: false })).toBeVisible()
  await retry.getByRole('button', { name: 'Reintentar', exact: true }).click()
  await expect(retry.getByRole('link', { name: 'Abrir', exact: true })).toHaveCount(1)
  await expect(retry.getByRole('button', { name: 'Reintentar', exact: true })).toHaveCount(0)
  const retried = (await overview()).messages.find((item: any) => item.envelope.subject === 'Retry one attachment')
  const retryHistory = await (await request.get(`${root}/messages/${retried.id}/history`, { headers })).json()
  expect(retryHistory.activities.some((event: any) => event.kind === 'retry_requested')).toBe(true)
  expect(retryHistory.activities.some((event: any) => event.kind === 'failed')).toBe(true)
  const after = await (await request.get(`${API}/_mail-test/state`)).json()
  expect(after.unchanged).toBe(true)
  expect(after.forbidden).toEqual([])
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(retry).toBeVisible()
  expect((await retry.boundingBox())?.width).toBeGreaterThan(300)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('mail-settings-mobile.png'), fullPage: true })
  await page.setViewportSize({ width: 1280, height: 900 })
  await message.getByRole('link', { name: 'Abrir', exact: true }).first().click()
  await expect(page.getByText('Recibido por correo · pay.pdf')).toBeVisible()
})
